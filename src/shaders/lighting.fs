#version 330

in vec2 fragTexCoord;
in vec4 fragColor;

uniform sampler2D texture0;
uniform sampler2D normalTexture;
uniform sampler2D shadowTexture;

uniform vec2 lightPos;
uniform vec2 resolution;
uniform vec2 framebufferScale;
uniform float lightRadius;
uniform vec3 lightColor;
uniform float lightIntensity;
uniform float ambient;
uniform int useShadows;
uniform int useScreenPosition;

out vec4 finalColor;

void main(){
    vec4 surfaceColor = texture(texture0, fragTexCoord) * fragColor;

    vec2 fragmentScreenPosition;

    if (useScreenPosition == 1){
        // Direct sprite drawing: trees
        fragmentScreenPosition = vec2(gl_FragCoord.x / framebufferScale.x, resolution.y - gl_FragCoord.y / framebufferScale.y);
    }
    else{
        // Fullscreen G-buffer
        fragmentScreenPosition = vec2(fragTexCoord.x * resolution.x, (1.0 - fragTexCoord.y) * resolution.y);
    }

    float distanceToLight = distance(fragmentScreenPosition, lightPos);
    
    float normalizedLightDistance = distanceToLight / lightRadius;

    float lightAttenuation = 1.0 - smoothstep(0.55, 1.0, normalizedLightDistance);

    // Visibility mask generated by ShadowRenderer2D.

    if (useShadows == 1){
        float shadowVisibility = texture(shadowTexture, fragTexCoord).r;
        lightAttenuation *= shadowVisibility;
    }

        float diffuseLighting = 1.0;

    // Ground pass: use the normal texture you already created.
    if (useScreenPosition == 0){
        vec3 surfaceNormal = texture(normalTexture, fragTexCoord).rgb;
        surfaceNormal = normalize(surfaceNormal * 2.0 - 1.0);

        // Give the light a height above the ground.
        float lightHeightAboveGround = lightRadius * 0.2;

        vec2 directionToLight2D = lightPos - fragmentScreenPosition;
        vec3 directionToLight3D = normalize(vec3(directionToLight2D.x, -directionToLight2D.y, lightHeightAboveGround));

        diffuseLighting = max(dot(surfaceNormal, directionToLight3D), 0.0);
    }

    float directLighting = lightAttenuation * diffuseLighting;
    float surfaceLuminance = dot(surfaceColor.rgb, vec3(0.2126, 0.7152, 0.0722));
    vec3 lightAffectedSurface = surfaceColor.rgb;
    
    // Keep the player's light and shadows, without the warm colour tint.
    // vec3 lit = albedo.rgb * ambient + lanternSurface * lightColor * lightIntensity * direct * 0.35;
    vec3 litColor = surfaceColor.rgb * ambient + lightAffectedSurface * lightIntensity * directLighting * 0.35;
    // Tiny, fixed brightness variation reduces visible gradient bands.
    float ditheringNoise = fract(52.9829189 * fract(dot(gl_FragCoord.xy, vec2(0.06711056, 0.00583715))));

    vec3 ditheredColor = litColor + vec3((ditheringNoise - 0.5) / 63.0);
    finalColor = vec4(clamp(ditheredColor, 0.0, 1.0), surfaceColor.a);
}
